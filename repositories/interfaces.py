"""Storage-independent contracts for FiniSpeak application data.

The protocols deliberately use the existing Firestore-shaped dictionaries so
controllers can migrate one domain at a time without changing API payloads.
Firebase Authentication and realtime signaling are outside these contracts.
"""

from typing import Any, Mapping, Protocol, Sequence


Document = dict[str, Any]


class AccountRepository(Protocol):
    def get(self, uid: str) -> Document | None: ...
    def all(self) -> Sequence[Document]: ...
    def find_by_email(self, email: str) -> Document | None: ...
    def find_by_phone(self, phone: str) -> Document | None: ...
    def update_status(self, uid: str, status: str) -> Document | None: ...
    def bootstrap(self, identity: Document, data: Mapping[str, Any]) -> Document: ...
    def update_profile(self, uid: str, data: Mapping[str, Any]) -> Document | None: ...


class TranslatorRepository(Protocol):
    def all(self) -> Sequence[Document]: ...
    def all_public(self) -> Sequence[Document]: ...
    def get(self, translator_id: str, public: bool = True) -> Document | None: ...
    def get_private(self, translator_id: str) -> Document: ...
    def search(self, **criteria: Any) -> Sequence[Document]: ...
    def pending_verification(self) -> Sequence[Document]: ...
    def set_verification(self, translator_id: str, status: str, reviewer_id: str, notes: str = "") -> Document | None: ...
    def update_availability(self, translator_id: str, availability: Mapping[str, Any]) -> Document | None: ...
    def save_profile(self, translator_id: str, public_data: Mapping[str, Any], private_data: Mapping[str, Any]) -> Document: ...
    def enroll(self, identity: Document, phone: str = "") -> Document: ...


class CallRepository(Protocol):
    def all(self) -> Sequence[Document]: ...
    def create(self, caller: Document, receiver: Document, **values: Any) -> Document: ...
    def get(self, call_id: str) -> Document | None: ...
    def for_user(self, uid: str) -> Sequence[Document]: ...
    def transition(self, call_id: str, next_state: str) -> Document | None: ...
    def request_translator(self, call_id: str, **values: Any) -> Document | None: ...
    def claim_translator(self, call_id: str, translator: Document) -> Document | None: ...


class ParticipantRepository(Protocol):
    def for_call(self, call_id: str) -> Sequence[Document]: ...
    def add(self, call_id: str, uid: str, role: str, display_name: str | None) -> Document: ...


class TranscriptRepository(Protocol):
    def for_call(self, call_id: str, limit: int = 500) -> Sequence[Document]: ...
    def add(self, call_id: str, transcript_id: str, data: Mapping[str, Any]) -> Document: ...


class ReviewRepository(Protocol):
    def all(self) -> Sequence[Document]: ...
    def for_interpreter(self, interpreter_id: str, visible_only: bool = True, limit: int = 20) -> Sequence[Document]: ...
    def create(self, interpreter_id: str, author: Document, call_id: str, rating: int, text: str) -> Document: ...
    def moderate(self, interpreter_id: str, review_id: str, status: str) -> Document | None: ...


class OrganizationRepository(Protocol):
    def all(self) -> Sequence[Document]: ...
    def create(self, data: Mapping[str, Any], actor_id: str) -> Document: ...
    def update(self, organization_id: str, data: Mapping[str, Any]) -> Document | None: ...


class ApiAccessRepository(Protocol):
    def create(self, data: Mapping[str, Any], actor_id: str) -> Document: ...
    def all(self) -> Sequence[Document]: ...
    def revoke(self, key_id: str, actor_id: str) -> Document | None: ...
    def authenticate(self, token: str) -> Document | None: ...
    def consume_quota(self, api_key: Document, now: Any = None) -> Document: ...
    def record_usage(self, api_key: Document, endpoint: str, method: str, status_code: int,
                     duration_ms: int, request_id: str) -> None: ...
    def usage_summary(self, limit: int = 500) -> Document: ...


class TaxonomyRepository(Protocol):
    def all_active(self) -> Document: ...
    def create(self, kind: str, record_id: str, name: str, extra: Mapping[str, Any] | None = None) -> Document: ...


class LanguageMetricsRepository(Protocol):
    def record(self, call_id: str, event_type: str, **values: Any) -> Document: ...
    def summary(self, limit: int = 2000) -> Document: ...
